BEGIN
  EXECUTE IMMEDIATE 'DROP TABLE LUDO_GAMES';
EXCEPTION
  WHEN OTHERS THEN
    IF SQLCODE != -942 THEN RAISE; END IF;
END;
/

CREATE TABLE LUDO_GAMES (
  GAME_ID VARCHAR2(36) PRIMARY KEY,
  STATUS VARCHAR2(20) NOT NULL,
  TURN_PLAYER VARCHAR2(10) NOT NULL,
  DICE_VALUE NUMBER(1) DEFAULT 0,
  GUEST_TOKENS VARCHAR2(20) NOT NULL,
  BOT_TOKENS VARCHAR2(20) NOT NULL,
  GUEST_SIXES NUMBER(1) DEFAULT 0,
  BOT_SIXES NUMBER(1) DEFAULT 0,
  MESSAGE VARCHAR2(500),
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
